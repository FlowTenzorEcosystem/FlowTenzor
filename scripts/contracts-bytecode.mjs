// Copies the compiled creation bytecode of the three FlowTenzor contracts into the site for /deploy.
// Run after a clean build (incremental via-ir builds can emit different bytes):
//   (cd contracts && ./setup.sh && forge build --force) && node scripts/contracts-bytecode.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const NAMES = ["ForecastOracle", "CallCredits", "ModelBond"];
let out = `// Generated by scripts/contracts-bytecode.mjs from contracts/src
// (solc 0.8.24, optimizer 200 runs, via-ir, evm paris, no metadata hash). Do not edit.
`;
for (const name of NAMES) {
  const artifact = JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url), "utf8"));
  const bytecode = artifact.bytecode.object;
  const sha = createHash("sha256").update(bytecode).digest("hex");
  out += `\n// ${name}: ${bytecode.length / 2 - 1} bytes, sha256 of the hex ${sha}\nexport const ${name.toUpperCase()}_BYTECODE = "${bytecode}";\n`;
  console.log(`${name} ${bytecode.length / 2 - 1} bytes, sha256 ${sha}`);
}
writeFileSync(new URL("../src/lib/onchain/bytecode.ts", import.meta.url), out);
